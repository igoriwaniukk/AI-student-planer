export function translate(lang, key, vars) {
  const table = dict[lang] || dict.pl;
  let str = table[key] ?? dict.pl[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}
