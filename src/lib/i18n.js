// Recurring-activity days and WEEK_DAYS labels are stored/matched as
// canonical Polish strings everywhere (Calendar matching, the AI's
// add_recurring_activity enum) — only their on-screen label changes with
// language, via this lookup.
export const DAY_KEY = {
  Poniedziałek: 'day.mon', Wtorek: 'day.tue', Środa: 'day.wed', Czwartek: 'day.thu',
  Piątek: 'day.fri', Sobota: 'day.sat', Niedziela: 'day.sun',
};

export function translate(lang, key, vars) {
  const table = dict[lang] || dict.pl;
  let str = table[key] ?? dict.pl[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}
